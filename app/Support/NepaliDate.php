    /**
     * Converts an AD date (Y-m-d, optionally with a time part) to its
     * BS equivalent in Y-m-d form. Returns null for empty/invalid input
     * or dates outside the supported table range (BS 1970–2100).
     */
    public static function adToBs(?string $adDate): ?string
    {
        $adDate = trim((string) $adDate);
        if ($adDate === '') {
            return null;
        }

        if (! preg_match('/^(\d{4})-(\d{2})-(\d{2})/', $adDate, $m)) {
            return null;
        }

        $targetTs = gmmktime(0, 0, 0, (int) $m[2], (int) $m[3], (int) $m[1]);
        $epochTs = gmmktime(0, 0, 0, self::AD_EPOCH['month'], self::AD_EPOCH['day'], self::AD_EPOCH['year']);
        if ($targetTs === false || $epochTs === false) {
            return null;
        }

        $daysDiff = (int) round(abs($targetTs - $epochTs) / 86400);

        $bs = self::BS_EPOCH;
        $bs['day'] += $daysDiff;

        while (true) {
            $monthLength = self::MONTH_LENGTHS[$bs['year']][$bs['month'] - 1] ?? null;
            if ($monthLength === null) {
                return null;
            }
            if ($bs['day'] <= $monthLength) {
                break;
            }
            $bs['day'] -= $monthLength;
            $bs['month']++;
            if ($bs['month'] > 12) {
                $bs['month'] = 1;
                $bs['year']++;
            }
        }

        return sprintf('%04d-%02d-%02d', $bs['year'], $bs['month'], $bs['day']);
    }

    /**
     * Converts a BS date (Y-m-d) to its AD equivalent in Y-m-d form.
     * Returns null for empty/invalid input or dates outside the
     * supported table range (BS 1970–2100).
     */
    public static function bsToAd(?string $bsDate): ?string
    {
        $bsDate = trim((string) $bsDate);
        if ($bsDate === '') {
            return null;
        }

        if (! preg_match('/^(\d{4})-(\d{2})-(\d{2})/', $bsDate, $m)) {
            return null;
        }

        $year = (int) $m[1];
        $month = (int) $m[2];
        $day = (int) $m[3];

        if ($month < 1 || $month > 12) {
            return null;
        }

        $targetDayNum = self::bsDayNumber($year, $month, $day);
        $epochDayNum = self::bsDayNumber(self::BS_EPOCH['year'], self::BS_EPOCH['month'], self::BS_EPOCH['day']);

        if ($targetDayNum === null || $epochDayNum === null) {
            return null;
        }

        $epochTs = gmmktime(0, 0, 0, self::AD_EPOCH['month'], self::AD_EPOCH['day'], self::AD_EPOCH['year']);
        $targetTs = $epochTs + ($targetDayNum - $epochDayNum) * 86400;

        return gmdate('Y-m-d', $targetTs);
    }

    /**
     * Days elapsed from BS 1970-01-01 (day 0) to the given BS date, used
     * as a common axis to diff two BS dates via the month-length table.
     */
    private static function bsDayNumber(int $year, int $month, int $day): ?int
    {
        if ($year < 1970 || ! isset(self::MONTH_LENGTHS[$year])) {
            return null;
        }

        $days = $day - 1;

        for ($y = 1970; $y < $year; $y++) {
            if (! isset(self::MONTH_LENGTHS[$y])) {
                return null;
            }
            $days += array_sum(self::MONTH_LENGTHS[$y]);
        }

        for ($m = 1; $m < $month; $m++) {
            $days += self::MONTH_LENGTHS[$year][$m - 1];
        }

        return $days;
    }
